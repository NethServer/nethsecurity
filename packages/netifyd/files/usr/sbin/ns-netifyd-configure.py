import argparse
import hashlib
import ipaddress
import json
import os
import subprocess
import sys

from euci import EUci
from jinja2 import BaseLoader, Environment

INTERFACES_FILE = '/etc/netifyd/interfaces.d/10-nfqueue.conf'

# one queue per core, each served by its own netifyd thread: past 8 there's no gain, only a bigger kernel backlog
QUEUE_INSTANCES = min(8, max(2, os.cpu_count() or 1))
LAN_QUEUE = 50
# fixed past the largest LAN range: an HA node still on the old 50-53/54-57 layout that gets this file synced
# leaves its firewall traffic unanalyzed, instead of classifying it as lan
WAN_QUEUE = 58

INTERFACES = f"""# Generated by ns-netifyd-configure on netifyd start, do not edit

[capture-interface-lan]
capture_type = nfqueue
role = lan
queue_id = {LAN_QUEUE}
queue_instances = {QUEUE_INSTANCES}
conntrack_counters = true

[capture-interface-wan]
capture_type = nfqueue
role = wan
queue_id = {WAN_QUEUE}
queue_instances = {QUEUE_INSTANCES}
conntrack_counters = true
"""

# Whole table, applied only by start and only when its version changed.
# The bypass sets are created empty here and filled by NFQ_BYPASS.
NFQ_TABLE = """
destroy table inet netifyd

table inet netifyd {
    comment "{{ version }}"

    set nfq_bypass_v4 { type ipv4_addr; flags interval; auto-merge; }
    set nfq_bypass_v6 { type ipv6_addr; flags interval; auto-merge; }

{%- if 'input' in firewall_chains %}

    # push input packets to userspace queues for DPI analysis
    chain nfq_input {
        type filter hook input priority filter + 10; policy accept;
        iifname lo accept

        # Skip untracked traffic
        ct state untracked accept
{%- if 'output' not in firewall_chains %}
        # Skip reply traffic for connections initiated by the firewall itself
        # (e.g. DNS responses, monitoring ping replies)
        ct direction reply accept
{%- endif %}
        # Accept traffic matching bypass set
        ip saddr @nfq_bypass_v4 accept
        ip daddr @nfq_bypass_v4 accept
        ip6 saddr @nfq_bypass_v6 accept
        ip6 daddr @nfq_bypass_v6 accept

        # Netifyd only analyzes the first 32 packets
        ct packets > 32 accept

        queue flags bypass to {{ wan_queues }}
    }
{%- endif %}

{%- if 'forward' in firewall_chains %}

    # push forward packets to userspace queues for DPI analysis
    chain nfq_forward {
        type filter hook forward priority filter + 10; policy accept;

        # Skip untracked traffic
        ct state untracked accept
        # Accept traffic matching bypass set
        ip saddr @nfq_bypass_v4 accept
        ip daddr @nfq_bypass_v4 accept
        ip6 saddr @nfq_bypass_v6 accept
        ip6 daddr @nfq_bypass_v6 accept

        # Netifyd only analyzes the first 32 packets
        ct packets > 32 accept

        queue flags bypass to {{ lan_queues }}
    }
{%- endif %}

{%- if 'output' in firewall_chains %}

    # push output packets to userspace queues for DPI analysis
    chain nfq_output {
        type filter hook output priority filter + 10; policy accept;
        oifname lo accept

        # Skip untracked traffic
        ct state untracked accept
        # Accept traffic matching bypass set
        ip saddr @nfq_bypass_v4 accept
        ip daddr @nfq_bypass_v4 accept
        ip6 saddr @nfq_bypass_v6 accept
        ip6 daddr @nfq_bypass_v6 accept

        # Netifyd only analyzes the first 32 packets
        ct packets > 32 accept

        queue flags bypass to {{ wan_queues }}
    }
{%- endif %}
}
"""

# Bypass sets, applied on every run. Never touches the chains, so it's safe while netifyd is running.
NFQ_BYPASS = """
table inet netifyd {
    set nfq_bypass_v4 { type ipv4_addr; flags interval; auto-merge; }
    set nfq_bypass_v6 { type ipv6_addr; flags interval; auto-merge; }
}
flush set inet netifyd nfq_bypass_v4
flush set inet netifyd nfq_bypass_v6
{%- if v4_elements %}
add element inet netifyd nfq_bypass_v4 { {{ v4_elements | join(', ') }} }
{%- endif %}
{%- if v6_elements %}
add element inet netifyd nfq_bypass_v6 { {{ v6_elements | join(', ') }} }
{%- endif %}
"""

# reload exit code when the table changed and netifyd must be restarted to rebuild it
EXIT_RESTART_NEEDED = 3


def render(template, **values):
    return Environment(loader=BaseLoader()).from_string(template).render(**values)


def get_firewall_chains(u):
    """Chains to analyze from netifyd.config.firewall_traffic, all of them when missing or invalid"""
    valid_chains = ['input', 'output', 'forward']
    firewall_chains = []
    for chain in u.get('netifyd', 'config', 'firewall_traffic', dtype=str, list=True, default=valid_chains):
        if chain in valid_chains:
            firewall_chains.append(chain)
        else:
            print(f"Warning: invalid firewall_traffic value '{chain}', ignoring. Valid values: {valid_chains}", file=sys.stderr)
    if not firewall_chains:
        print('Warning: no valid firewall_traffic chains configured, defaulting to all chains.', file=sys.stderr)
        firewall_chains = valid_chains
    return firewall_chains


def get_bypass_elements(u, option, version):
    """nft set elements from a bypass list, each entry is 'address[/prefix] [| description]'"""
    elements = []
    for entry in u.get('netifyd', 'config', option, dtype=str, list=True, default=[]):
        address, _, description = entry.partition('|')
        try:
            network = ipaddress.ip_network(address.strip(), strict=False)
        except ValueError:
            network = None
        if network is None or network.version != version:
            print(f"Warning: invalid {option} entry '{entry}', ignoring", file=sys.stderr)
            continue
        # nft comments can't hold double quotes and are capped at 128 characters
        description = description.strip().replace('"', '')[:128]
        elements.append(f'{network} comment "{description}"' if description else str(network))
    return elements


def get_table_version():
    """Comment of the inet netifyd table, None when the table is missing"""
    result = subprocess.run(['nft', '-j', 'list', 'table', 'inet', 'netifyd'], capture_output=True, text=True)
    if result.returncode != 0:
        return None
    for item in json.loads(result.stdout)['nftables']:
        if 'table' in item:
            return item['table'].get('comment')
    return None


def run_nft(commands):
    result = subprocess.run(['nft', '-f', '-'], input=commands, capture_output=True, text=True)
    if result.returncode != 0:
        print(f'Error applying nftables configuration: {result.stderr}', file=sys.stderr)
        sys.exit(1)


def main():
    parser = argparse.ArgumentParser(
        description='Configure the netifyd nfqueue capture: interfaces.d/10-nfqueue.conf and the inet netifyd '
        'nft table. The table comment is a hash of its rendered chains, to know when it no longer matches the '
        'configuration. The bypass sets are refreshed on every run.'
    )
    parser.add_argument('action', choices=['start', 'reload'], help=(
        'start: write 10-nfqueue.conf and rebuild the table if its version changed; '
        f'reload: never touch the chains, exit with {EXIT_RESTART_NEEDED} if the table version changed '
        'and netifyd must be restarted to rebuild it'
    ))
    args = parser.parse_args()

    u = EUci()
    table_values = {
        'firewall_chains': get_firewall_chains(u),
        'lan_queues': f'{LAN_QUEUE}-{LAN_QUEUE + QUEUE_INSTANCES - 1}',
        'wan_queues': f'{WAN_QUEUE}-{WAN_QUEUE + QUEUE_INSTANCES - 1}',
    }
    version = hashlib.sha1(render(NFQ_TABLE, version='', **table_values).encode()).hexdigest()[:12]
    table_changed = get_table_version() != version
    bypass = render(
        NFQ_BYPASS,
        v4_elements=get_bypass_elements(u, 'bypassv4', 4),
        v6_elements=get_bypass_elements(u, 'bypassv6', 6),
    )

    if args.action == 'reload':
        run_nft(bypass)
        if table_changed:
            print('netifyd nft table changed, netifyd must be restarted to rebuild it', file=sys.stderr)
            sys.exit(EXIT_RESTART_NEEDED)
        return

    with open(INTERFACES_FILE, 'w') as f:
        f.write(INTERFACES)
    if table_changed:
        # destroying a hooked chain drops the packets queued in it: fine here, netifyd isn't reading them yet
        run_nft(render(NFQ_TABLE, version=version, **table_values) + bypass)
    else:
        run_nft(bypass)


if __name__ == '__main__':
    main()
